pub(crate) fn active(request: &LinkedStoryRequest) -> bool {
    request.source_tags.is_some() || tables::config(request).is_some()
}

/// Original-revision owners whose /K and /Pg are regenerated by this verified
/// transaction. Used only to plan pruning; final removal allows no exemptions.
pub(crate) fn migration_source_nodes(
    input: &[u8],
    request: &LinkedStoryRequest,
) -> Result<BTreeSet<ObjectRef>> {
    if !active(request) {
        return Ok(BTreeSet::new());
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (store, root, index) = index_document(&engine, None)?;
    let pages = engine
        .document()
        .get_pages()?
        .into_iter()
        .map(|p| (p.object_number, p.generation_number))
        .collect();
    let lookup = Lookup::new(&store, root, &index, &pages)?;
    Ok(selection(&store, root, &index, &lookup, request)?
        .selected
        .into_iter()
        .collect())
}
fn semantic_text<'a>(request: &'a LinkedStoryRequest, id: &str) -> Option<&'a StorySemanticText> {
    request
        .source_tags
        .as_ref()
        .and_then(|tags| tags.semantic_text.get(id))
        .or_else(|| tables::text_review(request, id))
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TagReference {
    pub object: u32,
    #[serde(default)]
    pub generation: u16,
    /// Stable source marker assigned by this editor; object numbers are then
    /// diagnostic only and may change during a canonical save.
    #[serde(default)]
    pub key: Option<String>,
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StorySemanticText {
    /// Explicit None removes a previous alternate description/expansion.
    #[serde(default)]
    pub alternate: Option<String>,
    #[serde(default)]
    pub expansion: Option<String>,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StoryTagging {
    pub parent: TagReference,
    pub selected: Vec<TagReference>,
    /// Required for an empty selection; otherwise inferred from current /K.
    #[serde(default)]
    pub insert_at: Option<usize>,
    /// Reuse one selected element per paragraph. Explicit None creates a new P.
    /// Missing entries preserve source order only when counts match exactly.
    #[serde(default)]
    pub paragraph_sources: BTreeMap<String, Option<TagReference>>,
    #[serde(default)]
    pub new_roles: BTreeMap<String, String>,
    /// Required when reusing an element with Alt/E. These describe meaning,
    /// which cannot be inferred merely by replacing the visible glyphs.
    #[serde(default)]
    pub semantic_text: BTreeMap<String, StorySemanticText>,
    /// Exact image owners, separate from caption paragraphs. Entries for
    /// explicitly removed figures remain until the transaction is consumed.
    #[serde(default)]
    pub figures: BTreeMap<String, figures::FigureTagBinding>,
}
#[derive(Debug, Clone, Serialize)]
pub struct StoryTagSource {
    pub reference: TagReference,
    /// Includes shared-parent aliases as well as the element's primary key.
    pub stable_keys: Vec<String>,
    pub parent: Option<TagReference>,
    pub role: String,
    pub child_position: Option<usize>,
    pub page_mcids: Vec<(usize, usize)>,
    /// Structural candidate only. Mutation preflight separately verifies that
    /// every painted operand is selected and that no non-text paint is owned.
    pub text_leaf: bool,
    pub alternate: Option<String>,
    pub expansion: Option<String>,
}
fn semantic_string(store: &Store<'_>, dict: &PdfDictionary, name: &str) -> Result<Option<String>> {
    match dict.get(name).map(|v| store.resolve(v)).transpose()? {
        None | Some(PdfObject::Null) => Ok(None),
        Some(PdfObject::String(bytes)) => Ok(Some(crate::info::decode_pdf_text_string(&bytes))),
        _ => Err(fail("structural alternate/expansion is not a text string")),
    }
}
fn logical_string(value: &str) -> PdfObject {
    let mut bytes = vec![0xFE, 0xFF];
    for unit in value.encode_utf16() {
        bytes.extend_from_slice(&unit.to_be_bytes());
    }
    PdfObject::String(bytes)
}
fn key(story: &str, paragraph: &str) -> String {
    let mut h = Sha256::new();
    h.update((story.len() as u64).to_be_bytes());
    h.update(story.as_bytes());
    h.update(paragraph.as_bytes());
    format!("{:x}", h.finalize())
}
fn story_key(request: &LinkedStoryRequest) -> String {
    key(&request.story_id, "")
}
fn key_value(dict: &PdfDictionary, name: &str) -> Option<String> {
    dict.get(name)?
        .as_string()
        .and_then(|bytes| std::str::from_utf8(bytes).ok())
        .map(str::to_owned)
}
fn kids(dict: &PdfDictionary) -> Vec<PdfObject> {
    match dict.get("K") {
        None | Some(PdfObject::Null) => Vec::new(),
        Some(PdfObject::Array(v)) => v.clone(),
        Some(v) => vec![v.clone()],
    }
}
fn tag_ref(id: ObjectRef, dict: &PdfDictionary) -> TagReference {
    TagReference {
        object: id.0,
        generation: id.1,
        key: key_value(dict, "WFStoryTagKey"),
    }
}
struct Lookup {
    keys: BTreeMap<String, ObjectRef>,
    non_leaf: BTreeSet<ObjectRef>,
    positions: BTreeMap<ObjectRef, usize>,
}
impl Lookup {
    fn new(
        store: &Store<'_>,
        root: ObjectRef,
        index: &StructureIndex,
        pages: &BTreeSet<ObjectRef>,
    ) -> Result<Self> {
        let mut result = Self {
            keys: BTreeMap::new(),
            non_leaf: index.objects.values().copied().collect(),
            positions: BTreeMap::new(),
        };
        for (&scope, items) in &index.marked {
            if !pages.contains(&scope) {
                result.non_leaf.extend(items.values().copied());
            }
        }
        for node in index.nodes.iter().copied().chain(std::iter::once(root)) {
            crate::cancel::check_current_cancel("story tag identity index")?;
            let dict = store.dict(node)?;
            if let Some(parent) = dict.get_reference("P") {
                result.non_leaf.insert(parent);
            }
            let mut keys = key_value(&dict, "WFStoryTagKey")
                .into_iter()
                .collect::<Vec<_>>();
            if let Some(parents) = dict.get("WFStoryParentKeys").and_then(PdfObject::as_dict) {
                keys.extend(parents.iter().map(|(key, _)| key.to_string()));
            }
            for key in keys {
                if result.keys.insert(key, node).is_some_and(|old| old != node) {
                    return Err(fail("persistent tag key has multiple owners"));
                }
            }
            for (i, kid) in kids(&dict).iter().enumerate() {
                if let Some(id) = kid.as_reference() {
                    if index.nodes.contains(&id) {
                        result.positions.insert(id, i);
                    }
                }
            }
        }
        Ok(result)
    }
}
fn resolve_tag(
    root: ObjectRef,
    index: &StructureIndex,
    lookup: &Lookup,
    target: &TagReference,
) -> Result<ObjectRef> {
    if let Some(key) = &target.key {
        if key.len() != 64 || !key.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(fail("invalid persistent tag key"));
        }
        lookup
            .keys
            .get(key)
            .copied()
            .ok_or_else(|| fail("persistent story tag is missing"))
    } else {
        let id = (target.object, target.generation);
        if id != root && !index.nodes.contains(&id) {
            return Err(fail("tag selection is not in the reachable structure tree"));
        }
        Ok(id)
    }
}
pub fn sources(input: &[u8]) -> Result<Vec<StoryTagSource>> {
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    if !engine
        .document()
        .get_catalog()?
        .contains_key("StructTreeRoot")
    {
        return Ok(Vec::new());
    }
    validate_parent_tree(input)?;
    let (store, root, index) = index_document(&engine, None)?;
    let pages = engine
        .document()
        .get_pages()?
        .iter()
        .map(|p| ((p.object_number, p.generation_number), p.page_number))
        .collect::<BTreeMap<_, _>>();
    let page_ids = pages.keys().copied().collect();
    let lookup = Lookup::new(&store, root, &index, &page_ids)?;
    let mut page_mcids = BTreeMap::<ObjectRef, Vec<(usize, usize)>>::new();
    for (scope, items) in &index.marked {
        if let Some(&page) = pages.get(scope) {
            for (&mcid, &owner) in items {
                page_mcids.entry(owner).or_default().push((page, mcid));
            }
        }
    }
    let mut out = Vec::new();
    let mut stable_keys = BTreeMap::<ObjectRef, Vec<String>>::new();
    for (key, &node) in &lookup.keys {
        stable_keys.entry(node).or_default().push(key.clone());
    }
    for &node in &index.nodes {
        let dict = store.dict(node)?;
        let parent = dict.get_reference("P");
        out.push(StoryTagSource {
            reference: tag_ref(node, &dict),
            stable_keys: stable_keys.remove(&node).unwrap_or_default(),
            parent: parent
                .map(|id| store.dict(id).map(|d| tag_ref(id, &d)))
                .transpose()?,
            role: dict.get_name("S").unwrap_or("").into(),
            child_position: lookup.positions.get(&node).copied(),
            page_mcids: page_mcids.remove(&node).unwrap_or_default(),
            text_leaf: !lookup.non_leaf.contains(&node),
            alternate: semantic_string(&store, &dict, "Alt")?,
            expansion: semantic_string(&store, &dict, "E")?,
        });
    }
    Ok(out)
}

/// Private bridge used by the two-story Figure transfer transaction.  It moves
/// one already-owned Figure or approved contentless Figure subtree between two
/// saved story intervals without changing its `/K`, semantic strings or other
/// structure attributes.  The
/// target story's ordinary finish transaction subsequently replaces `/K` with
/// the MCID of the relocated native image.
///
/// Keeping this operation here (rather than editing serialized StoryTagging
/// alone) makes the physical structure tree authoritative: both parent `/K`
/// arrays, the Figure `/P` pointer, stable story identity and ParentTree are
/// changed and reopened before either updated saved model is published.
pub(crate) fn transfer_figure_owner(
    input: &[u8],
    source: &LinkedStoryRequest,
    target: &LinkedStoryRequest,
    source_figure_id: &str,
    target_figure_id: &str,
    target_caption_paragraph: &str,
) -> Result<(Vec<u8>, StoryTagging, StoryTagging)> {
    if source.story_id == target.story_id
        || source_figure_id.is_empty()
        || target_figure_id.is_empty()
        || target_caption_paragraph.is_empty()
        || source.table_layout.is_some()
        || target.table_layout.is_some()
    {
        return Err(fail("invalid tagged Figure owner transfer"));
    }
    // Validate the exact current paint-to-structure association before moving
    // a node.  General ParentTree validity alone does not prove that the saved
    // Figure owns the selected image occurrence.
    validate_selection(input, source)?;
    validate_selection(input, target)?;

    let mut source_tags = source
        .source_tags
        .clone()
        .ok_or_else(|| fail("tagged Figure transfer source has no structure model"))?;
    let mut target_tags = target
        .source_tags
        .clone()
        .ok_or_else(|| fail("tagged Figure transfer target has no structure model"))?;
    if target_tags.figures.contains_key(target_figure_id) {
        return Err(fail("target Figure structure identity already exists"));
    }
    let mut figure_binding = source_tags
        .figures
        .remove(source_figure_id)
        .ok_or_else(|| fail("source Figure structure identity is missing"))?;
    let source_reference = figure_binding
        .source
        .clone()
        .ok_or_else(|| fail("source Figure has no reusable structure owner"))?;
    let caption_reference = target_tags
        .paragraph_sources
        .get(target_caption_paragraph)
        .and_then(|reference| reference.clone())
        .ok_or_else(|| fail("target caption has no reusable structure owner"))?;

    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (mut store, root, index) = index_document(&engine, None)?;
    let page_ids = engine
        .document()
        .get_pages()?
        .iter()
        .map(|page| (page.object_number, page.generation_number))
        .collect();
    let lookup = Lookup::new(&store, root, &index, &page_ids)?;
    let source_parent = resolve_tag(root, &index, &lookup, &source_tags.parent)?;
    let target_parent = resolve_tag(root, &index, &lookup, &target_tags.parent)?;
    let figure = resolve_tag(root, &index, &lookup, &source_reference)?;
    let caption = resolve_tag(root, &index, &lookup, &caption_reference)?;
    let approved_subtree = if figure_binding.preserve_semantic_subtree {
        if figure_binding.delete_semantic_subtree
            || figure_binding.clone_semantic_subtree_for_reused_form
            || figure_binding.split_reused_form_semantics
            || figure_binding.outbound_ref_split.is_some()
            || figure_binding.inbound_ref_split.is_some()
        {
            return Err(fail(
                "tagged Figure transfer cannot carry unconsumed subtree/split authority",
            ));
        }
        Some(figures::validate_semantic_subtree(&store, &index, figure)?)
    } else {
        None
    };
    if figure == caption
        || (approved_subtree.is_none() && lookup.non_leaf.contains(&figure))
        || !figures::figure_role(&store, root, figure)?
        || store.dict(figure)?.get_reference("P") != Some(source_parent)
        || store.dict(caption)?.get_reference("P") != Some(target_parent)
    {
        return Err(fail(
            "tagged Figure transfer requires an exact page-owned Figure leaf or approved contentless subtree and a target caption leaf",
        ));
    }

    let resolve_selected = |tags: &StoryTagging| -> Result<Vec<ObjectRef>> {
        tags.selected
            .iter()
            .map(|reference| resolve_tag(root, &index, &lookup, reference))
            .collect()
    };
    let mut source_selected = resolve_selected(&source_tags)?;
    let mut target_selected = resolve_selected(&target_tags)?;
    let source_slots = source_selected
        .iter()
        .enumerate()
        .filter(|(_, node)| **node == figure)
        .map(|(slot, _)| slot)
        .collect::<Vec<_>>();
    let caption_slots = target_selected
        .iter()
        .enumerate()
        .filter(|(_, node)| **node == caption)
        .map(|(slot, _)| slot)
        .collect::<Vec<_>>();
    if source_slots.len() != 1
        || caption_slots.len() != 1
        || target_selected.contains(&figure)
        || source_selected.contains(&caption)
    {
        return Err(fail(
            "tagged Figure transfer source/target selection ownership is ambiguous",
        ));
    }
    let source_slot = source_slots[0];
    let caption_slot = caption_slots[0];

    let mut source_children = kids(&store.dict(source_parent)?);
    let source_child_slots = source_children
        .iter()
        .enumerate()
        .filter(|(_, child)| child.as_reference() == Some(figure))
        .map(|(slot, _)| slot)
        .collect::<Vec<_>>();
    if source_child_slots.len() != 1 {
        return Err(fail("source Figure is not one exact direct child"));
    }
    source_children.remove(source_child_slots[0]);

    if source_parent == target_parent {
        let caption_child_slots = source_children
            .iter()
            .enumerate()
            .filter(|(_, child)| child.as_reference() == Some(caption))
            .map(|(slot, _)| slot)
            .collect::<Vec<_>>();
        if caption_child_slots.len() != 1 {
            return Err(fail("target caption is not one exact direct child"));
        }
        source_children.insert(caption_child_slots[0], reference(figure));
        let mut parent = store.dict(source_parent)?;
        parent.insert("K", PdfObject::Array(source_children));
        store.replace_dict(source_parent, parent)?;
    } else {
        let mut source_dict = store.dict(source_parent)?;
        source_dict.insert("K", PdfObject::Array(source_children));
        store.replace_dict(source_parent, source_dict)?;

        let mut target_children = kids(&store.dict(target_parent)?);
        let caption_child_slots = target_children
            .iter()
            .enumerate()
            .filter(|(_, child)| child.as_reference() == Some(caption))
            .map(|(slot, _)| slot)
            .collect::<Vec<_>>();
        if caption_child_slots.len() != 1
            || target_children
                .iter()
                .any(|child| child.as_reference() == Some(figure))
        {
            return Err(fail(
                "target caption/Figure direct-child ownership is ambiguous",
            ));
        }
        target_children.insert(caption_child_slots[0], reference(figure));
        let mut target_dict = store.dict(target_parent)?;
        target_dict.insert("K", PdfObject::Array(target_children));
        store.replace_dict(target_parent, target_dict)?;
    }

    let mut figure_dict = store.dict(figure)?;
    figure_dict.insert("P", reference(target_parent));
    figure_dict.insert(
        "WFStoryID",
        PdfObject::String(story_key(target).into_bytes()),
    );
    store.replace_dict(figure, figure_dict.clone())?;

    source_tags.selected.remove(source_slot);
    source_selected.remove(source_slot);
    let moved_reference = tag_ref(figure, &figure_dict);
    target_tags
        .selected
        .insert(caption_slot, moved_reference.clone());
    target_selected.insert(caption_slot, figure);
    figure_binding.source = Some(moved_reference);
    target_tags
        .figures
        .insert(target_figure_id.to_owned(), figure_binding);

    // Recompute both stored insertion points from the final physical sibling
    // arrays.  When both stories share a parent, removing a source sibling can
    // shift the target interval even though its relative order is unchanged.
    let set_start =
        |store: &Store<'_>, parent: ObjectRef, selected: &[ObjectRef]| -> Result<usize> {
            let children = kids(&store.dict(parent)?);
            if selected.is_empty() {
                return Err(fail("tagged Figure transfer cannot empty a story interval"));
            }
            let start = children
                .iter()
                .position(|child| child.as_reference() == Some(selected[0]))
                .ok_or_else(|| fail("transferred story interval is missing"))?;
            if start
                .checked_add(selected.len())
                .is_none_or(|end| end > children.len())
                || children[start..start + selected.len()]
                    .iter()
                    .map(PdfObject::as_reference)
                    .ne(selected.iter().copied().map(Some))
            {
                return Err(fail("transferred story interval is no longer contiguous"));
            }
            Ok(start)
        };
    source_tags.insert_at = Some(set_start(&store, source_parent, &source_selected)?);
    target_tags.insert_at = Some(set_start(&store, target_parent, &target_selected)?);

    let candidate = write_store(store)?;
    let (output, _) = rebuild_owner_trees(&candidate, None)?;
    validate_parent_tree(&output)?;
    Ok((output, source_tags, target_tags))
}

struct Selection {
    parent: ObjectRef,
    selected: Vec<ObjectRef>,
    start: usize,
    targets: BTreeMap<String, Option<ObjectRef>>,
    figures: BTreeMap<String, Option<ObjectRef>>,
    figure_ocr_owners: BTreeMap<String, BTreeMap<String, ObjectRef>>,
}
fn selection(
    store: &Store<'_>,
    root: ObjectRef,
    index: &StructureIndex,
    lookup: &Lookup,
    request: &LinkedStoryRequest,
) -> Result<Selection> {
    if tables::config(request).is_some() {
        return tables::selection(store, root, index, lookup, request);
    }
    let config = request
        .source_tags
        .as_ref()
        .ok_or_else(|| fail("tagged stories require an approved source_tags selection"))?;
    if config.selected.len() > 100_000
        || config.paragraph_sources.len() > 100_000
        || config.new_roles.len() > 100_000
        || config.semantic_text.len() > 100_000
    {
        return Err(fail("story tag selection budget exceeded"));
    }
    let semantic_bytes = config.semantic_text.values().fold(0usize, |total, text| {
        total
            .saturating_add(text.alternate.as_ref().map_or(0, String::len))
            .saturating_add(text.expansion.as_ref().map_or(0, String::len))
    });
    if semantic_bytes > 4_000_000 {
        return Err(fail("story semantic text aggregate budget exceeded"));
    }
    let parent = resolve_tag(root, index, lookup, &config.parent)?;
    let selected = config
        .selected
        .iter()
        .map(|v| resolve_tag(root, index, lookup, v))
        .collect::<Result<Vec<_>>>()?;
    let unique = selected.iter().copied().collect::<BTreeSet<_>>();
    if unique.len() != selected.len() || unique.contains(&parent) {
        return Err(fail("duplicate/cyclic story tag selection"));
    }
    let children = kids(&store.dict(parent)?);
    let start = if selected.is_empty() {
        config
            .insert_at
            .ok_or_else(|| fail("empty story tag selection needs insert_at"))?
    } else {
        children
            .iter()
            .position(|v| v.as_reference() == Some(selected[0]))
            .ok_or_else(|| fail("selected tag is not a direct child of the approved parent"))?
    };
    if start > children.len()
        || start
            .checked_add(selected.len())
            .is_none_or(|end| end > children.len())
        || children[start..start + selected.len()]
            .iter()
            .map(PdfObject::as_reference)
            .ne(selected.iter().copied().map(Some))
        || config.insert_at.is_some_and(|i| i != start)
    {
        return Err(fail(
            "story tag selection must match a contiguous current sibling interval",
        ));
    }
    let mut ancestor = Some(parent);
    let mut seen = BTreeSet::new();
    while let Some(node) = ancestor {
        if !seen.insert(node) {
            return Err(fail("cyclic story tag ancestors"));
        }
        let dict = store.dict(node)?;
        if dict
            .get("ActualText")
            .is_some_and(|v| !matches!(v, PdfObject::Null))
        {
            return Err(fail(
                "ancestor ActualText needs an explicit semantic text rewrite before story reflow",
            ));
        }
        ancestor = if node == root {
            None
        } else {
            dict.get_reference("P")
        };
    }
    let story = story_key(request);
    for &node in &selected {
        let dict = store.dict(node)?;
        if dict.get_reference("P") != Some(parent)
            || key_value(&dict, "WFStoryID").is_some_and(|id| id != story)
        {
            return Err(fail("selected tag belongs to another parent/story"));
        }
    }
    let paragraph_ids = request
        .paragraphs
        .iter()
        .map(|p| p.id.as_str())
        .collect::<BTreeSet<_>>();
    if config
        .paragraph_sources
        .keys()
        .chain(config.new_roles.keys())
        .chain(config.semantic_text.keys())
        .any(|id| !paragraph_ids.contains(id.as_str()))
    {
        return Err(fail("tag binding names a missing paragraph"));
    }
    let mut targets = BTreeMap::new();
    let mut used = BTreeSet::new();
    for (position, paragraph) in request.paragraphs.iter().enumerate() {
        let target = match config.paragraph_sources.get(&paragraph.id) {
            Some(Some(value)) => Some(resolve_tag(root, index, lookup, value)?),
            Some(None) => None,
            None if selected.len() == request.paragraphs.len() => Some(selected[position]),
            None if selected.is_empty() => None,
            None => {
                return Err(fail(
                    "changed paragraph count requires explicit paragraph_sources reuse/create decisions",
                ));
            }
        };
        if let Some(node) = target {
            if !unique.contains(&node) || !used.insert(node) {
                return Err(fail("paragraph tag reuse must be unique and selected"));
            }
            if config.new_roles.contains_key(&paragraph.id) {
                return Err(fail(
                    "new_roles cannot change the role of a reused source element",
                ));
            }
            let dict = store.dict(node)?;
            if (semantic_string(store, &dict, "Alt")?.is_some()
                || semantic_string(store, &dict, "E")?.is_some())
                && !config.semantic_text.contains_key(&paragraph.id)
            {
                return Err(fail(
                    "reused paragraph has alternate/expanded text; approve semantic_text replacement or removal explicitly",
                ));
            }
        }
        if config.semantic_text.get(&paragraph.id).is_some_and(|text| {
            text.alternate.as_ref().is_some_and(|v| v.len() > 1_000_000)
                || text.expansion.as_ref().is_some_and(|v| v.len() > 1_000_000)
        }) {
            return Err(fail("paragraph semantic text budget exceeded"));
        }
        let role = config
            .new_roles
            .get(&paragraph.id)
            .map(String::as_str)
            .unwrap_or("P");
        if role.is_empty() || role.len() > 127 || role.bytes().any(|b| !b.is_ascii_alphanumeric()) {
            return Err(fail("invalid new paragraph role"));
        }
        targets.insert(paragraph.id.clone(), target);
    }
    // Do not strand explicit inter-element references on removed owners.
    let mut removed_figure_descendants = BTreeSet::new();
    let figure_targets = figures::select(
        store,
        root,
        index,
        lookup,
        request,
        &unique,
        &mut used,
        &mut removed_figure_descendants,
    )?;
    let figure_ocr_owners = figures::select_ocr_owners(
        store,
        root,
        index,
        lookup,
        request,
        parent,
        &unique,
        &used,
        &figure_targets,
    )?;
    let mut removed = unique.difference(&used).copied().collect::<BTreeSet<_>>();
    removed.extend(removed_figure_descendants);
    ensure_unreferenced_removals(store, index, &removed)?;
    Ok(Selection {
        parent,
        selected,
        start,
        targets,
        figures: figure_targets,
        figure_ocr_owners,
    })
}

fn ensure_unreferenced_removals(
    store: &Store<'_>,
    index: &StructureIndex,
    removed: &BTreeSet<ObjectRef>,
) -> Result<()> {
    if removed.is_empty() {
        return Ok(());
    }
    let mut removed_ids = BTreeSet::new();
    for &node in removed {
        if let Some(value) = store.dict(node)?.get("ID") {
            if let PdfObject::String(bytes) = store.resolve(value)? {
                removed_ids.insert(bytes);
            }
        }
    }
    fn contains(
        store: &Store<'_>,
        index: &StructureIndex,
        value: &PdfObject,
        ids: &BTreeSet<ObjectRef>,
        removed_ids: &BTreeSet<Vec<u8>>,
        headers: bool,
        seen: &mut BTreeSet<(ObjectRef, bool)>,
        depth: usize,
        budget: &mut usize,
    ) -> Result<bool> {
        if depth > 64 || *budget == 0 {
            return Err(fail("structure reference budget exceeded"));
        }
        *budget -= 1;
        if let Some(id) = value.as_reference() {
            if ids.contains(&id) {
                return Ok(true);
            }
            // Other structure owners are inspected independently. Resolve
            // indirect attribute dictionaries and /Ref arrays, not just direct
            // values, but do not walk paint/resource graphs through page refs.
            if index.nodes.contains(&id) || !seen.insert((id, headers)) {
                return Ok(false);
            }
            let value = store.get(id)?;
            if matches!(&value, PdfObject::Stream { .. })
                || value.as_dict().is_some_and(|dict| {
                    matches!(
                        dict.get_name("Type"),
                        Some(
                            "Page"
                                | "Pages"
                                | "StructTreeRoot"
                                | "Catalog"
                                | "Font"
                                | "XObject"
                                | "Annot"
                        )
                    )
                })
            {
                return Ok(false);
            }
            return contains(
                store,
                index,
                &value,
                ids,
                removed_ids,
                headers,
                seen,
                depth + 1,
                budget,
            );
        }
        match value {
            PdfObject::String(bytes) if headers && removed_ids.contains(bytes) => return Ok(true),
            PdfObject::Array(v) => {
                for v in v {
                    if contains(
                        store,
                        index,
                        v,
                        ids,
                        removed_ids,
                        headers,
                        seen,
                        depth + 1,
                        budget,
                    )? {
                        return Ok(true);
                    }
                }
            }
            PdfObject::Dictionary(d) => {
                for (name, v) in d.iter() {
                    if contains(
                        store,
                        index,
                        v,
                        ids,
                        removed_ids,
                        headers || name == "Headers",
                        seen,
                        depth + 1,
                        budget,
                    )? {
                        return Ok(true);
                    }
                }
            }
            _ => {}
        }
        Ok(false)
    }
    let mut budget = 1_000_000;
    let mut seen = BTreeSet::new();
    let resolver = attributes::Resolver::new(store)?;
    let mut attribute_budget = attributes::Budget::default();
    for &node in index.nodes.iter().filter(|node| !removed.contains(*node)) {
        crate::cancel::check_current_cancel("story structural relationship preservation")?;
        let dict = store.dict(node)?;
        for (name, value) in dict.iter() {
            if !removed.is_empty()
                && name != "P"
                && name != "K"
                && name != "A"
                && name != "C"
                && contains(
                    store,
                    index,
                    value,
                    removed,
                    &removed_ids,
                    name == "Headers",
                    &mut seen,
                    0,
                    &mut budget,
                )?
            {
                return Err(fail(
                    "removed structure owner is referenced by another element; explicit reference migration required",
                ));
            }
        }
        for value in resolver.effective(store, &dict, &mut attribute_budget)? {
            if contains(
                store,
                index,
                &value,
                removed,
                &removed_ids,
                false,
                &mut seen,
                0,
                &mut budget,
            )? {
                return Err(fail(
                    "removed structure owner is referenced through an effective attribute/class; explicit migration required",
                ));
            }
        }
    }
    Ok(())
}

struct Mark {
    stream: ObjectRef,
    start: usize,
    end: usize,
    mcid: Option<usize>,
    mcid_range: Option<(usize, usize)>,
    dictionary_end: Option<usize>,
    paragraph: Option<String>,
    frame: Option<String>,
    safe: bool,
    artifact: bool,
    closing: Option<(ObjectRef, usize, usize)>,
    enclosing_frame: Option<String>,
    image_key: Option<String>,
    figure: Option<String>,
    actual_text: bool,
    actual_text_nonempty: bool,
    authored_table: Option<String>,
    authored_cell: Option<String>,
}
struct TextOccurrence {
    stream: ObjectRef,
    stream_index: usize,
    range: [usize; 2],
    bytes_empty: bool,
    marks: Vec<usize>,
}
struct PageMarks {
    marks: Vec<Mark>,
    text: Vec<TextOccurrence>,
    nontext: Vec<PaintOccurrence>,
}
struct PaintOccurrence {
    stream: ObjectRef,
    stream_index: usize,
    range: [usize; 2],
    marks: Vec<usize>,
    image: bool,
}
fn property_string(operands: &[LexicalToken], name: &str) -> Result<Option<String>> {
    match marked_property(operands, name)?.map(|v| &v.kind) {
        None | Some(LexicalKind::Null) => Ok(None),
        Some(LexicalKind::String(_, bytes)) => Ok(Some(
            std::str::from_utf8(bytes)
                .map_err(|_| fail("invalid story marker encoding"))?
                .into(),
        )),
        _ => Err(fail("story marker is not a string")),
    }
}

fn property_pdf_string(operands: &[LexicalToken], name: &str) -> Result<Option<String>> {
    match marked_property(operands, name)?.map(|value| &value.kind) {
        None | Some(LexicalKind::Null) => Ok(None),
        Some(LexicalKind::String(_, bytes)) => Ok(Some(crate::info::decode_pdf_text_string(bytes))),
        _ => Err(fail("authored typed-cell marker is not a PDF string")),
    }
}
fn content_marks<'a, I>(engine: &ContentEngine, contents: I) -> Result<PageMarks>
where
    I: IntoIterator<Item = (ObjectRef, usize, &'a PdfDictionary)>,
{
    let reader = engine.document().reader();
    let mut decoded = ContentScopes::new(engine);
    let mut result = PageMarks {
        marks: Vec::new(),
        text: Vec::new(),
        nontext: Vec::new(),
    };
    let mut stack: Vec<usize> = Vec::new();
    let mut scope_slots = 0usize;
    for (stream, stream_index, resources) in contents {
        let data = decoded.stream(stream)?;
        let mut operands = Vec::new();
        let mut inline_start = None;
        for token in lex_content(&data)? {
            let LexicalKind::Word(operator) = &token.kind else {
                operands.push(token);
                continue;
            };
            match operator.as_str() {
                "BDC" | "BMC" => {
                    if stack.len() >= 4096 || result.marks.len() >= MAX_NODES {
                        return Err(fail("story marked-content budget exceeded"));
                    }
                    let tag = match operands.first().map(|v| &v.kind) {
                        Some(LexicalKind::Name(s)) => s.as_str(),
                        _ => return Err(fail("missing marked-content tag")),
                    };
                    let property = if operator == "BDC" {
                        marked_property(&operands, "MCID")?
                    } else {
                        None
                    };
                    let mut mcid = match property.map(|v| &v.kind) {
                        None | Some(LexicalKind::Null) => None,
                        Some(LexicalKind::Number(n))
                            if n.is_finite()
                                && *n >= 0.0
                                && *n <= MAX_MCID as f64
                                && n.fract() == 0.0 =>
                        {
                            Some(*n as usize)
                        }
                        _ => return Err(fail("invalid story MCID")),
                    };
                    let named = if operator == "BDC" {
                        match operands.get(1).map(|v| &v.kind) {
                            Some(LexicalKind::Name(name)) => Some(name),
                            _ => None,
                        }
                    } else {
                        None
                    };
                    let mut named_actual = false;
                    let mut named_actual_nonempty = false;
                    if let Some(name) = named {
                        let properties = resources
                            .get("Properties")
                            .ok_or_else(|| fail("missing marked property resources"))?;
                        let properties = reader.resolve(properties.clone())?;
                        let value = properties
                            .as_dict()
                            .and_then(|d| d.get(name))
                            .ok_or_else(|| fail("missing named marked property"))?;
                        let value = reader.resolve(value.clone())?;
                        let dictionary = value
                            .as_dict()
                            .ok_or_else(|| fail("invalid named marked property"))?;
                        if let Some(value) = dictionary.get("ActualText") {
                            let value = reader.resolve(value.clone())?;
                            named_actual = !matches!(&value, PdfObject::Null);
                            named_actual_nonempty = match &value {
                                PdfObject::Null => false,
                                PdfObject::String(bytes) => {
                                    !crate::info::decode_pdf_text_string(bytes).is_empty()
                                }
                                _ => true,
                            };
                        }
                        mcid = dictionary
                            .get_integer("MCID")
                            .map(|v| usize::try_from(v).map_err(|_| fail("negative MCID")))
                            .transpose()?;
                    }
                    let actual_property = if operator == "BDC" {
                        marked_property(&operands, "ActualText")?
                    } else {
                        None
                    };
                    let actual = named_actual || actual_property.is_some();
                    let actual_text_nonempty = named_actual_nonempty
                        || actual_property.is_some_and(|value| match &value.kind {
                            LexicalKind::Null => false,
                            LexicalKind::String(_, bytes) => {
                                !crate::info::decode_pdf_text_string(bytes).is_empty()
                            }
                            _ => true,
                        });
                    let frame = if operator == "BDC" {
                        property_string(&operands, "WFStoryFrame")?
                    } else {
                        None
                    };
                    let paragraph = if operator == "BDC" {
                        property_string(&operands, "WFStoryParagraph")?
                    } else {
                        None
                    };
                    let authored_table = if operator == "BDC" {
                        property_pdf_string(&operands, "WFTableID")?
                    } else {
                        None
                    };
                    let authored_cell = if operator == "BDC" {
                        property_pdf_string(&operands, "WFCellID")?
                    } else {
                        None
                    };
                    if authored_table.is_some() != authored_cell.is_some() {
                        return Err(fail(
                            "authored typed-cell marker has incomplete ownership identity",
                        ));
                    }
                    let enclosing_frame = stack
                        .iter()
                        .rev()
                        .find_map(|&i| result.marks[i].frame.clone());
                    result.marks.push(Mark {
                        stream,
                        start: operands.first().map_or(token.start, |v| v.start),
                        end: token.end,
                        mcid,
                        mcid_range: property.map(|v| (v.start, v.end)),
                        dictionary_end: operands
                            .last()
                            .filter(|v| matches!(v.kind, LexicalKind::DictionaryEnd))
                            .map(|v| v.start),
                        paragraph,
                        frame: frame.clone(),
                        safe: tag != "OC"
                            && (mcid.is_some() || tag == "Span" && (actual || frame.is_some())),
                        artifact: tag == "Artifact" && mcid.is_none(),
                        closing: None,
                        enclosing_frame,
                        image_key: if tag == "WFImageFragment" {
                            property_string(&operands, "Key")?
                        } else {
                            None
                        },
                        figure: if operator == "BDC" {
                            property_string(&operands, "WFStoryFigure")?
                        } else {
                            None
                        },
                        actual_text: actual,
                        actual_text_nonempty,
                        authored_table,
                        authored_cell,
                    });
                    stack.push(result.marks.len() - 1);
                }
                "EMC" => {
                    let open = stack
                        .pop()
                        .ok_or_else(|| fail("unbalanced story marked content"))?;
                    result.marks[open].closing = Some((stream, token.start, token.end));
                }
                "Tj" | "TJ" | "'" | "\"" => {
                    for value in &operands {
                        if let LexicalKind::String(_, bytes) = &value.kind {
                            if result.text.len() >= 1_000_000 {
                                return Err(fail("story source text operand budget exceeded"));
                            }
                            scope_slots = scope_slots.saturating_add(stack.len());
                            if scope_slots > 2_000_000 {
                                return Err(fail("story scope provenance memory budget exceeded"));
                            }
                            result.text.push(TextOccurrence {
                                stream,
                                stream_index,
                                range: [value.start, value.end],
                                bytes_empty: bytes.is_empty(),
                                marks: stack.clone(),
                            });
                        }
                    }
                }
                "BI" if inline_start.replace(token.start).is_some() => {
                    return Err(fail("nested inline image"));
                }
                "Do" | "sh" | "S" | "s" | "f" | "F" | "f*" | "B" | "B*" | "b" | "b*" | "EI" => {
                    scope_slots = scope_slots.saturating_add(stack.len());
                    if scope_slots > 2_000_000 || result.nontext.len() >= 1_000_000 {
                        return Err(fail("story paint provenance memory budget exceeded"));
                    }
                    result.nontext.push(PaintOccurrence {
                        stream,
                        stream_index,
                        range: [
                            if operator == "EI" {
                                inline_start
                                    .take()
                                    .ok_or_else(|| fail("unmatched inline image end"))?
                            } else {
                                operands.first().map_or(token.start, |v| v.start)
                            },
                            token.end,
                        ],
                        marks: stack.clone(),
                        image: matches!(operator.as_str(), "Do" | "EI"),
                    });
                }
                _ => {}
            }
            operands.clear();
        }
        if inline_start.is_some() {
            return Err(fail("incomplete inline image in tagged page"));
        }
    }
    if !stack.is_empty() {
        return Err(fail("unterminated story marked content"));
    }
    Ok(result)
}

fn page_marks(engine: &ContentEngine, page: &crate::document::PdfPage) -> Result<PageMarks> {
    content_marks(
        engine,
        page.contents
            .iter()
            .enumerate()
            .map(|(stream_index, &stream)| (stream, stream_index, &page.resources)),
    )
}

fn form_marks(
    engine: &ContentEngine,
    stream: ObjectRef,
    stream_index: usize,
    resources: &PdfDictionary,
) -> Result<PageMarks> {
    content_marks(engine, std::iter::once((stream, stream_index, resources)))
}

pub(crate) fn validate_selection(input: &[u8], request: &LinkedStoryRequest) -> Result<()> {
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let tagged = engine
        .document()
        .get_catalog()?
        .contains_key("StructTreeRoot");
    if !tagged {
        if active(request) {
            return Err(fail(
                "source tag ownership requires an existing structure tree",
            ));
        }
        return Ok(());
    }
    validate_parent_tree(input)?;
    let (store, root, index) = index_document(&engine, None)?;
    let pages = engine.document().get_pages()?;
    let page_ids = pages
        .iter()
        .map(|p| (p.object_number, p.generation_number))
        .collect::<BTreeSet<_>>();
    let lookup = Lookup::new(&store, root, &index, &page_ids)?;
    let selection = selection(&store, root, &index, &lookup, request)?;
    let selected = selection.selected.iter().copied().collect::<BTreeSet<_>>();
    let figure_owners = selection
        .figures
        .values()
        .flatten()
        .copied()
        .collect::<BTreeSet<_>>();
    let figure_ocr_owners = selection
        .figure_ocr_owners
        .values()
        .flat_map(|owners| owners.values().copied())
        .collect::<BTreeSet<_>>();
    for &node in &selected {
        if lookup.non_leaf.contains(&node)
            && !figure_owners.contains(&node)
            && !figure_ocr_owners.contains(&node)
        {
            return Err(fail(
                "story source element includes nested structure, OBJR or Form-owned content; explicit subtree migration required",
            ));
        }
    }
    let figure_sources = figures::source_bindings(input, request, &selection, &store, &index)?;
    let mut seen_figures = BTreeSet::new();
    let mut ocr_selection = figures::ocr::OcrSelection::new(request, &selection)?;
    let frame_pages = request
        .frames
        .iter()
        .map(|f| f.page)
        .chain(figure_sources.iter().map(|s| s.page))
        .collect::<BTreeSet<_>>();
    for page in &pages {
        let page_id = (page.object_number, page.generation_number);
        let owned = index
            .marked
            .get(&page_id)
            .map(|m| {
                m.iter()
                    .filter(|(_, owner)| selected.contains(*owner))
                    .map(|(m, _)| *m)
                    .collect::<BTreeSet<_>>()
            })
            .unwrap_or_default();
        if !owned.is_empty() && !frame_pages.contains(&page.page_number) {
            return Err(fail(
                "selected tag owns content outside approved story frame pages",
            ));
        }
        if !frame_pages.contains(&page.page_number) {
            continue;
        }
        let marks = page_marks(&engine, page)?;
        let model = crate::advanced_editing::analyze_multi_run_text_range(input, page.page_number)?;
        let ocr_page =
            ocr_selection.page(page.page_number, page_id, &marks, &index, &model, request)?;
        let spans = model
            .source_spans
            .iter()
            .map(|s| (s.span_id.as_str(), s))
            .collect::<BTreeMap<_, _>>();
        let frames = request
            .frames
            .iter()
            .filter(|f| f.page == page.page_number)
            .collect::<Vec<_>>();
        let owner_keys = frames
            .iter()
            .filter_map(|f| f.owner.as_ref().map(|o| o.key.as_str()))
            .collect::<BTreeSet<_>>();
        let mut ranges = frames
            .iter()
            .filter(|f| f.owner.is_none())
            .map(|f| f.logical_range)
            .collect::<Vec<_>>();
        ranges.sort_unstable();
        if ranges.iter().any(|r| r[0] >= r[1])
            || ranges.windows(2).any(|pair| pair[0][1] > pair[1][0])
        {
            return Err(fail(
                "initial tagged frames require disjoint nonempty source ranges; reuse owned empty frames for insertion",
            ));
        }
        let selected_range = |span: [usize; 2]| -> Option<[usize; 2]> {
            let i = ranges.partition_point(|range| range[0] < span[1]);
            if i > 0 && ranges[i - 1][1] > span[0] {
                Some(ranges[i - 1])
            } else {
                None
            }
        };
        // /ActualText owns one logical string even when several source glyph
        // operands paint it. Analysis assigns the logical range to the first
        // operand and intentionally gives the remaining operands empty ranges.
        // Once that logical owner is wholly selected, every source operand in
        // the same immutable owner must travel with it; treating the empty
        // followers as unrelated text leaves stale paint and rejects valid
        // tagged Figures.
        let selected_actual_text_sources = model
            .source_spans
            .iter()
            .filter(|span| selected_range(span.logical_range).is_some())
            .filter_map(|span| span.direct_actual_text_source.as_deref())
            .collect::<BTreeSet<_>>();
        let mut covered = BTreeSet::new();
        for occurrence in &marks.text {
            crate::cancel::check_current_cancel("tagged story source coverage")?;
            if ocr_page.contains(occurrence) {
                continue; // separately proved complete Figure OCR ownership
            }
            let span_id = format!(
                "p{}:s{}:o{}",
                page.page_number, occurrence.stream_index, occurrence.range[0]
            );
            let span = spans.get(span_id.as_str());
            if !occurrence.bytes_empty
                && occurrence.marks.iter().any(|i| {
                    marks.marks[*i]
                        .mcid
                        .and_then(|m| index.marked.get(&page_id).and_then(|v| v.get(&m)))
                        .is_some_and(|owner| figure_owners.contains(owner))
                })
            {
                return Err(fail(
                    "selected Figure owner contains text; caption/subtree migration must be explicit",
                ));
            }
            let in_owned = occurrence.marks.iter().any(|i| {
                marks.marks[*i]
                    .frame
                    .as_deref()
                    .is_some_and(|key| owner_keys.contains(key))
            });
            let selected_text = in_owned
                || span.is_some_and(|span| {
                    selected_range(span.logical_range).is_some()
                        || span
                            .direct_actual_text_source
                            .as_deref()
                            .is_some_and(|owner| selected_actual_text_sources.contains(owner))
                });
            let tag_selected = occurrence
                .marks
                .iter()
                .any(|i| marks.marks[*i].mcid.is_some_and(|m| owned.contains(&m)));
            if tag_selected && !selected_text && !occurrence.bytes_empty {
                return Err(fail(
                    "selected structure element contains text outside the approved ranges",
                ));
            }
            if selected_text {
                if occurrence.marks.iter().any(|i| {
                    let mark = &marks.marks[*i];
                    let owned_table_artifact = in_owned
                        && request.table_layout.is_some()
                        && mark.artifact
                        && mark
                            .enclosing_frame
                            .as_deref()
                            .is_some_and(|key| owner_keys.contains(key));
                    (!mark.safe && !owned_table_artifact)
                        || marks.marks[*i].mcid.is_some_and(|m| !owned.contains(&m))
                }) {
                    return Err(fail(
                        "story text has unapproved marked-content or optional-content ownership",
                    ));
                }
                if !in_owned
                    && span.is_some_and(|span| {
                        let actual_text_owner_selected = span
                            .direct_actual_text_source
                            .as_deref()
                            .is_some_and(|owner| selected_actual_text_sources.contains(owner));
                        !actual_text_owner_selected
                            && selected_range(span.logical_range).is_none_or(|range| {
                                range[0] > span.logical_range[0] || span.logical_range[1] > range[1]
                            })
                    })
                {
                    return Err(fail(
                        "tagged story selection must contain complete source text operands",
                    ));
                }
                if let Some(span) = span {
                    covered.insert(span.span_id.clone());
                }
            }
        }
        figures::validate_paint(
            page.page_number,
            page_id,
            &marks,
            &index,
            &selected,
            &figure_sources,
            &ocr_page,
            &mut seen_figures,
        )?;
        figures::validate_nested_paint(
            &engine,
            page.page_number,
            request,
            &index,
            &figure_sources,
            &mut ocr_selection,
            &mut seen_figures,
        )?;
        if model.source_spans.iter().any(|span| {
            selected_range(span.logical_range).is_some() && !covered.contains(&span.span_id)
        }) {
            return Err(fail(
                "selected source text lacks verified marked-content provenance",
            ));
        }
    }
    if seen_figures.len() != figure_sources.len() {
        return Err(fail("tagged figure source coverage is incomplete"));
    }
    ocr_selection.finish()?;
    Ok(())
}

pub(crate) fn attach_preview(
    request: &LinkedStoryRequest,
    preview: &mut LinkedStoryPreview,
) -> Result<()> {
    for frame in &mut preview.frames {
        if frame.lines.len() != frame.paragraph_ids.len() {
            return Err(fail("story line/paragraph provenance mismatch"));
        }
        for (line, id) in frame.lines.iter_mut().zip(&frame.paragraph_ids) {
            line.tag_owner =
                (active(request) && !line.artifact).then(|| key(&request.story_id, id));
        }
    }
    if request.source_tags.is_some() {
        preview.exact_limits.push("Approved paragraph leaf roles/order are migrated with line MCIDs; not arbitrary subtree inference or PDF/UA certification".into());
    }
    if !request.figures.is_empty() && request.source_tags.is_some() {
        preview.exact_limits.push("Explicit page-owned or Form-MCR Figure owners migrate with separate caption paragraphs and reviewed alternate text. A bounded semantic-only descendant tree can be retained without flattening when every child is contentless and uniquely parented; valid page bindings follow the destination. Explicit complete-subtree approval removes that contentless tree only when no surviving relationship targets any member. Reused-Form splitting can copy-on-write clone a separately approved contentless tree, rebuilding parent links, rewriting internal Figure/subtree /Ref links and dropping clone-only IDs/page bindings; external subtree relationships apply the same explicit outbound and incoming split policies as the Figure root. References between multiple Figure trees split in one request use a coordinated clone map, preserving selected-to-selected and residual-to-residual topology. A reused Form occurrence otherwise requires an explicit semantic split that preserves residual Figure and, when selected, ordered content-only OCR-owner leaves. Outbound /Ref ownership requires move, retain or copy authority; incoming /Ref owners require follow, retarget or reference-both authority and are rewritten as one batch. Bounded nested direct/indirect array graphs are topology-preserving and copy-on-write; cycles, excessive graphs, non-array indirect containers and non-structure leaves refuse. Invisible OCR can move through exact page-owned or nested capture; selected spans may remain Figure-owned or be partitioned across explicitly selected content-only P/Span siblings on a page or Form. Not PDF/UA certification".into());
    }
    if tables::config(request).is_some() {
        preview.exact_limits.push("Approved table, row-group and paragraph-path owners migrate with line MCIDs and class attributes; cell IDs stay separate from block leaves, shared ancestors require consistent order, repeated headers remain artifacts; not nested-table inference or PDF/UA certification".into());
    }
    Ok(())
}
fn write_store(store: Store<'_>) -> Result<Vec<u8>> {
    write_incremental_update(
        store.reader,
        store
            .updates
            .into_iter()
            .map(|((number, generation), object)| IncrementalObject {
                number,
                generation,
                object,
            })
            .collect(),
    )
}
type StreamPatches = BTreeMap<ObjectRef, Vec<(usize, usize, Vec<u8>)>>;
fn stage_stream_patches(
    store: &mut Store<'_>,
    changed: &mut BTreeSet<ObjectRef>,
    patches: StreamPatches,
) -> Result<()> {
    for (stream, mut edits) in patches {
        if !changed.insert(stream) {
            return Err(fail(
                "shared tagged stream must be isolated before migration",
            ));
        }
        let object = store.get(stream)?;
        let decoded = decode_stream_lossless_with_limits(
            &object,
            store.reader,
            &DecodeLimits {
                max_decoded_bytes_per_stream: MAX_STREAM,
                ..Default::default()
            },
        )?;
        if decoded.status != StreamDecodeStatus::Complete {
            return Err(fail("opaque story tag stream"));
        }
        let data = decoded.data;
        edits.sort_by_key(|(start, end, _)| (*start, *end));
        if edits.windows(2).any(|p| p[0].1 > p[1].0) {
            return Err(fail("overlapping story tag patches"));
        }
        let mut length = data.len();
        for (start, end, bytes) in &edits {
            if start > end || *end > data.len() {
                return Err(fail("tag patch outside source stream"));
            }
            length = length
                .checked_sub(end - start)
                .and_then(|n| n.checked_add(bytes.len()))
                .ok_or_else(|| fail("tag patch size overflow"))?;
        }
        if length > MAX_STREAM as usize {
            return Err(fail("tagged story output stream budget exceeded"));
        }
        let mut patched = Vec::with_capacity(length);
        let mut cursor = 0;
        for (start, end, bytes) in edits {
            crate::cancel::check_current_cancel("tagged story atomic stream rewrite")?;
            if start < cursor {
                return Err(fail("overlapping tag patches"));
            }
            patched.extend_from_slice(&data[cursor..start]);
            patched.extend(bytes);
            cursor = end;
        }
        patched.extend_from_slice(&data[cursor..]);
        let raw = crate::filters::flate_encode_cancellable(&patched, 6)?;
        let mut dict = object
            .as_stream()
            .ok_or_else(|| fail("tag target is not a stream"))?
            .0
            .clone();
        dict.insert("Filter", PdfObject::Name("FlateDecode".into()));
        dict.remove("DecodeParms");
        dict.insert("Length", PdfObject::Integer(raw.len() as i64));
        store
            .updates
            .insert(stream, PdfObject::Stream { dict, raw });
    }
    Ok(())
}
pub(crate) fn prepare(input: &[u8], request: &LinkedStoryRequest) -> Result<Vec<u8>> {
    if !active(request) {
        return Ok(input.to_vec());
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (mut store, root, index) = index_document(&engine, None)?;
    let page_ids = engine
        .document()
        .get_pages()?
        .iter()
        .map(|p| (p.object_number, p.generation_number))
        .collect();
    let lookup = Lookup::new(&store, root, &index, &page_ids)?;
    let selection = selection(&store, root, &index, &lookup, request)?;
    // Detach only preflight-approved source wrappers before glyph deletion.
    // Named property resources can be shared; never change those dictionaries.
    // Stripping the occurrence delimiters prevents old ActualText from
    // overriding the intermediate deletion's extraction postcondition. The
    // existing /K graph remains private until finish assigns replacement MCIDs.
    // The caller isolates shared content occurrences before reaching here.
    let selected = selection.selected.iter().copied().collect::<BTreeSet<_>>();
    let mut changed = BTreeSet::new();
    let figure_owners = selection
        .figures
        .values()
        .flatten()
        .copied()
        .collect::<BTreeSet<_>>();
    let nested_sources = if request.figures.is_empty() && request.figure_removals.is_empty() {
        Vec::new()
    } else {
        crate::image_fragments::stories::staged_nested_sources(input, &request.story_id)?
    };
    let mut expected_nested = BTreeSet::new();
    let mut observed_nested = BTreeSet::new();
    for (clone, source) in nested_sources {
        crate::cancel::check_current_cancel("tagged nested Figure delimiter migration")?;
        let source_mcids = index
            .marked
            .get(&source)
            .into_iter()
            .flat_map(|items| items.iter())
            .filter(|(_, owner)| figure_owners.contains(*owner))
            .map(|(mcid, _)| *mcid)
            .collect::<BTreeSet<_>>();
        expected_nested.extend(source_mcids.iter().map(|mcid| (source, *mcid)));
        let object = store.get(clone)?;
        let mut dictionary = object
            .as_stream()
            .ok_or_else(|| fail("tagged nested Figure clone is not a stream"))?
            .0
            .clone();
        if dictionary.get_name("Subtype") != Some("Form")
            || dictionary.get_reference("WFNestedImageSource") != Some(source)
        {
            return Err(fail("tagged nested Figure clone receipt changed"));
        }
        let resources = match dictionary.get("Resources") {
            None | Some(PdfObject::Null) => PdfDictionary::empty(),
            Some(value) => store
                .resolve(value)?
                .as_dict()
                .cloned()
                .ok_or_else(|| fail("tagged nested Figure resources are invalid"))?,
        };
        let marks = form_marks(&engine, clone, 0, &resources)?;
        let mut patches = StreamPatches::new();
        for mark in marks
            .marks
            .iter()
            .filter(|mark| mark.mcid.is_some_and(|mcid| source_mcids.contains(&mcid)))
        {
            let mcid = mark
                .mcid
                .ok_or_else(|| fail("tagged nested Figure MCID disappeared"))?;
            if !observed_nested.insert((source, mcid)) {
                return Err(fail(
                    "tagged nested Figure MCID appears in more than one live clone",
                ));
            }
            patches
                .entry(clone)
                .or_default()
                .push((mark.start, mark.end, Vec::new()));
            let (stream, start, end) = mark
                .closing
                .ok_or_else(|| fail("unclosed tagged nested Figure owner"))?;
            if stream != clone {
                return Err(fail("tagged nested Figure mark crosses a Form stream"));
            }
            patches
                .entry(stream)
                .or_default()
                .push((start, end, Vec::new()));
        }
        dictionary.remove("WFNestedImageSource");
        store.replace_dict(clone, dictionary)?;
        stage_stream_patches(&mut store, &mut changed, patches)?;
    }
    if observed_nested != expected_nested {
        return Err(fail(
            "tagged nested Figure clone omitted an approved Form MCID",
        ));
    }
    for page in engine.document().get_pages()? {
        let page_id = (page.object_number, page.generation_number);
        let owned = index
            .marked
            .get(&page_id)
            .map(|items| {
                items
                    .iter()
                    .filter(|(_, owner)| selected.contains(*owner))
                    .map(|(id, _)| *id)
                    .collect::<BTreeSet<_>>()
            })
            .unwrap_or_default();
        if owned.is_empty() {
            continue;
        }
        let marks = page_marks(&engine, &page)?;
        let mut patches = StreamPatches::new();
        for mark in marks
            .marks
            .iter()
            .filter(|m| m.mcid.is_some_and(|id| owned.contains(&id)))
        {
            patches
                .entry(mark.stream)
                .or_default()
                .push((mark.start, mark.end, Vec::new()));
            let (stream, start, end) = mark.closing.ok_or_else(|| fail("unclosed source tag"))?;
            patches
                .entry(stream)
                .or_default()
                .push((start, end, Vec::new()));
        }
        stage_stream_patches(&mut store, &mut changed, patches)?;
    }
    let story = story_key(request);
    let catalog_id = store
        .reader
        .root_reference()
        .ok_or_else(|| fail("missing story tag catalog"))?;
    let mut catalog = store.dict(catalog_id)?;
    if catalog.contains_key("WFStoryTagTransaction") {
        return Err(fail("unfinished tag transaction marker in source document"));
    }
    let mut targets = PdfDictionary::empty();
    let mut ordered = Vec::new();
    for p in &request.paragraphs {
        let owner_key = key(&request.story_id, &p.id);
        let node = if let Some(node) = selection.targets[&p.id] {
            node
        } else {
            let mut dict = PdfDictionary::empty();
            dict.insert("Type", PdfObject::Name("StructElem".into()));
            dict.insert(
                "S",
                PdfObject::Name(
                    tables::new_role(request, &p.id)
                        .or_else(|| {
                            request
                                .source_tags
                                .as_ref()
                                .and_then(|tags| tags.new_roles.get(&p.id).cloned())
                        })
                        .unwrap_or_else(|| "P".into()),
                ),
            );
            dict.insert("P", reference(selection.parent));
            store.add(PdfObject::Dictionary(dict))?
        };
        let mut dict = store.dict(node)?;
        dict.insert(
            "WFStoryTagKey",
            PdfObject::String(owner_key.as_bytes().to_vec()),
        );
        dict.insert("WFStoryID", PdfObject::String(story.as_bytes().to_vec()));
        store.replace_dict(node, dict)?;
        targets.insert(owner_key.clone(), reference(node));
        ordered.push(PdfObject::String(owner_key.into_bytes()));
    }
    let (figure_residuals, figure_inbound_refs) = figures::stage(
        &mut store,
        &index,
        request,
        &selection,
        &story,
        &mut targets,
    )?;
    let mut parent = store.dict(selection.parent)?;
    let mut parent_keys = parent
        .get("WFStoryParentKeys")
        .and_then(PdfObject::as_dict)
        .cloned()
        .unwrap_or_default();
    parent_keys.insert(story.clone(), PdfObject::Boolean(true));
    parent.insert("WFStoryParentKeys", PdfObject::Dictionary(parent_keys));
    store.replace_dict(selection.parent, parent)?;
    let mut txn = PdfDictionary::empty();
    txn.insert("Story", PdfObject::String(story.into_bytes()));
    txn.insert("Parent", reference(selection.parent));
    txn.insert(
        "Source",
        PdfObject::Array(selection.selected.iter().map(|id| reference(*id)).collect()),
    );
    txn.insert("Targets", PdfObject::Dictionary(targets));
    txn.insert("Order", PdfObject::Array(ordered));
    txn.insert("Start", PdfObject::Integer(selection.start as i64));
    txn.insert(
        "FigureResiduals",
        PdfObject::Array(
            figure_residuals
                .into_iter()
                .map(PdfObject::Dictionary)
                .collect(),
        ),
    );
    txn.insert(
        "FigureInboundRefs",
        PdfObject::Array(
            figure_inbound_refs
                .into_iter()
                .map(PdfObject::Dictionary)
                .collect(),
        ),
    );
    tables::stage(&mut store, root, &index, &lookup, request, &mut txn)?;
    catalog.insert("WFStoryTagTransaction", PdfObject::Dictionary(txn));
    store.replace_dict(catalog_id, catalog)?;
    write_store(store)
}

pub(crate) fn finish(
    input: &[u8],
    request: &LinkedStoryRequest,
    preview: &LinkedStoryPreview,
) -> Result<(Vec<u8>, Option<StoryTagging>, Option<tables::TableTagging>)> {
    if !active(request) {
        return Ok((input.to_vec(), None, None));
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (mut store, root, index) = index_document(&engine, None)?;
    let catalog_id = store
        .reader
        .root_reference()
        .ok_or_else(|| fail("missing story tag catalog"))?;
    let mut catalog = store.dict(catalog_id)?;
    let txn = catalog
        .get("WFStoryTagTransaction")
        .and_then(PdfObject::as_dict)
        .cloned()
        .ok_or_else(|| fail("missing private story tag transaction"))?;
    if key_value(&txn, "Story").as_deref() != Some(story_key(request).as_str()) {
        return Err(fail("wrong story tag transaction"));
    }
    let parent = txn
        .get_reference("Parent")
        .ok_or_else(|| fail("missing tag parent"))?;
    let source = txn
        .get("Source")
        .and_then(PdfObject::as_array)
        .ok_or_else(|| fail("missing tag source set"))?
        .iter()
        .map(|v| {
            v.as_reference()
                .ok_or_else(|| fail("invalid source tag reference"))
        })
        .collect::<Result<Vec<_>>>()?;
    let selected = source.iter().copied().collect::<BTreeSet<_>>();
    let targets = txn
        .get("Targets")
        .and_then(PdfObject::as_dict)
        .ok_or_else(|| fail("missing target tag owners"))?;
    let residual_figures =
        figures::residuals(&store, root, &index, request, &txn, targets, parent)?;
    let expected = preview
        .frames
        .iter()
        .enumerate()
        .map(|(i, frame)| {
            (
                (
                    frame.frame.page,
                    crate::linked_stories::frame_key(&request.story_id, &frame.frame.id),
                ),
                (
                    i,
                    frame
                        .lines
                        .iter()
                        .filter(|line| line.tag_owner.is_some())
                        .collect::<Vec<_>>(),
                ),
            )
        })
        .collect::<BTreeMap<_, _>>();
    let mut observed = BTreeMap::<(usize, String), usize>::new();
    let expected_figures = figures::expected(request, preview)?;
    let mut observed_figures = BTreeMap::new();
    let mut locations = BTreeMap::<String, Vec<(usize, usize, PdfObject)>>::new();
    let mut changed_streams = BTreeSet::new();
    for page in engine.document().get_pages()? {
        let page_id = (page.object_number, page.generation_number);
        let marks = page_marks(&engine, &page)?;
        let old = index
            .marked
            .get(&page_id)
            .map(|m| {
                m.iter()
                    .filter(|(_, owner)| selected.contains(*owner))
                    .map(|(id, _)| *id)
                    .collect::<BTreeSet<_>>()
            })
            .unwrap_or_default();
        let mut used = marks
            .marks
            .iter()
            .filter_map(|m| m.mcid)
            .collect::<BTreeSet<_>>();
        let mut patches = BTreeMap::<ObjectRef, Vec<(usize, usize, Vec<u8>)>>::new();
        let mut next = 0;
        figures::stamp_page(
            page.page_number,
            page_id,
            &marks,
            &expected_figures,
            &mut observed_figures,
            &mut used,
            &mut next,
            &mut patches,
        )?;
        for mark in &marks.marks {
            let ours = mark
                .paragraph
                .as_ref()
                .filter(|key| targets.contains_key(key));
            let remove = mark.mcid.is_some_and(|id| old.contains(&id));
            if !remove && ours.is_none() {
                continue;
            }
            if ours.is_none() {
                // The approved old owner contains no unselected text/artwork.
                // Remove only its delimiters; keep its graphics-state and paint
                // operators. This also removes stale direct/named ActualText
                // without modifying a shared property resource.
                patches
                    .entry(mark.stream)
                    .or_default()
                    .push((mark.start, mark.end, Vec::new()));
                let (stream, start, end) =
                    mark.closing.ok_or_else(|| fail("unclosed source tag"))?;
                patches
                    .entry(stream)
                    .or_default()
                    .push((start, end, Vec::new()));
                continue;
            }
            let value = if let Some(owner) = ours {
                let frame_key = mark
                    .enclosing_frame
                    .clone()
                    .ok_or_else(|| fail("paragraph tag is outside its approved frame owner"))?;
                let frame_identity = (page.page_number, frame_key);
                let (frame_index, lines) = expected
                    .get(&frame_identity)
                    .ok_or_else(|| fail("paragraph tag is in an unapproved frame"))?;
                let ordinal = observed.entry(frame_identity).or_default();
                if lines.get(*ordinal).and_then(|line| line.tag_owner.as_ref()) != Some(owner) {
                    return Err(fail(
                        "paragraph marker order disagrees with approved story lines",
                    ));
                }
                while used.contains(&next) {
                    next += 1;
                }
                if next > MAX_MCID {
                    return Err(fail("story page MCID capacity exceeded"));
                }
                let mcid = next;
                used.insert(mcid);
                let mut mcr = PdfDictionary::empty();
                mcr.insert("Type", PdfObject::Name("MCR".into()));
                mcr.insert("Pg", reference(page_id));
                mcr.insert("MCID", PdfObject::Integer(mcid as i64));
                locations.entry(owner.clone()).or_default().push((
                    *frame_index,
                    *ordinal,
                    PdfObject::Dictionary(mcr),
                ));
                *ordinal += 1;
                mcid.to_string().into_bytes()
            } else {
                b"null".to_vec()
            };
            if let Some((start, end)) = mark.mcid_range {
                patches
                    .entry(mark.stream)
                    .or_default()
                    .push((start, end, value));
            } else if let Some(end) = mark.dictionary_end {
                let mut bytes = b" /MCID ".to_vec();
                bytes.extend(value);
                bytes.push(b' ');
                patches
                    .entry(mark.stream)
                    .or_default()
                    .push((end, end, bytes));
            } else {
                return Err(fail(
                    "generated paragraph tags require direct property dictionaries",
                ));
            }
        }
        stage_stream_patches(&mut store, &mut changed_streams, patches)?;
    }
    if expected
        .iter()
        .any(|(key, (_, lines))| observed.get(key).copied().unwrap_or(0) != lines.len())
    {
        return Err(fail(
            "generated tag ownership disagrees with approved paragraph line plan",
        ));
    }
    if observed_figures.len() != expected_figures.len() {
        return Err(fail(
            "generated Figure ownership disagrees with approved figure plan",
        ));
    }
    let mut order = Vec::new();
    let mut rebound_sources = BTreeMap::new();
    let paragraph_attributes = if request.source_tags.is_some() {
        Some(attributes::Resolver::new(&store)?)
    } else {
        None
    };
    let mut attribute_budget = attributes::Budget::default();
    for p in &request.paragraphs {
        let owner_key = key(&request.story_id, &p.id);
        let node = targets
            .get_reference(&owner_key)
            .ok_or_else(|| fail("missing generated tag owner"))?;
        let mut dict = store.dict(node)?;
        let mut parts = locations.remove(&owner_key).unwrap_or_default();
        parts.sort_by_key(|(frame, line, _)| (*frame, *line));
        dict.insert(
            "K",
            PdfObject::Array(parts.into_iter().map(|(_, _, item)| item).collect()),
        );
        dict.remove("Pg");
        dict.insert("ActualText", logical_string(&p.text));
        if let Some(text) = semantic_text(request, &p.id) {
            for (name, value) in [("Alt", &text.alternate), ("E", &text.expansion)] {
                if let Some(value) = value {
                    dict.insert(name, logical_string(value));
                } else {
                    dict.remove(name);
                }
            }
        }
        if let Some(resolver) = &paragraph_attributes {
            resolver.rewrite_flow(
                &mut store,
                &mut dict,
                None,
                request.writing_mode,
                p.rtl,
                &mut attribute_budget,
            )?;
        }
        store.replace_dict(node, dict)?;
        order.push(reference(node));
        rebound_sources.insert(
            p.id.clone(),
            Some(TagReference {
                object: node.0,
                generation: node.1,
                key: Some(owner_key),
            }),
        );
    }
    if tables::config(request).is_some() {
        let rebound = tables::finish(&mut store, request, &txn, &rebound_sources)?;
        catalog.remove("WFStoryTagTransaction");
        store.replace_dict(catalog_id, catalog)?;
        let candidate = write_store(store)?;
        let (output, _) = rebuild_owner_trees(&candidate, None)?;
        return Ok((output, None, Some(rebound)));
    }
    let rebound_figures = figures::finish(
        &mut store,
        &index,
        request,
        targets,
        &mut observed_figures,
        paragraph_attributes
            .as_ref()
            .ok_or_else(|| fail("missing story attribute resolver"))?,
        &mut attribute_budget,
        preview,
    )?;
    if !request.figures.is_empty() {
        order = residual_figures.iter().copied().map(reference).collect();
        let captions = request
            .figures
            .iter()
            .map(|f| (f.caption_paragraph.as_str(), f))
            .collect::<BTreeMap<_, _>>();
        for p in &request.paragraphs {
            if let Some(figure) = captions.get(p.id.as_str()) {
                let tag = rebound_figures[&figure.id]
                    .source
                    .as_ref()
                    .ok_or_else(|| fail("missing rebound Figure"))?;
                order.push(reference((tag.object, tag.generation)));
            }
            let tag = rebound_sources[&p.id]
                .as_ref()
                .ok_or_else(|| fail("missing rebound paragraph"))?;
            order.push(reference((tag.object, tag.generation)));
        }
    }
    let start = usize::try_from(
        txn.get_integer("Start")
            .ok_or_else(|| fail("missing tag insertion point"))?,
    )
    .map_err(|_| fail("invalid tag insertion point"))?;
    let mut parent_dict = store.dict(parent)?;
    let mut children = kids(&parent_dict);
    if start
        .checked_add(source.len())
        .is_none_or(|end| end > children.len())
        || children[start..start + source.len()]
            .iter()
            .map(PdfObject::as_reference)
            .ne(source.iter().copied().map(Some))
    {
        return Err(fail("tag sibling interval changed inside transaction"));
    }
    children.splice(start..start + source.len(), order);
    parent_dict.insert("K", PdfObject::Array(children));
    if parent_dict.get_name("Type") == Some("StructElem") {
        if let Some(resolver) = &paragraph_attributes {
            resolver.rewrite(&mut store, &mut parent_dict, None, &mut attribute_budget)?;
        }
    }
    store.replace_dict(parent, parent_dict)?;
    catalog.remove("WFStoryTagTransaction");
    store.replace_dict(catalog_id, catalog)?;
    let candidate = write_store(store)?;
    let (output, _) = rebuild_owner_trees(&candidate, None)?;
    let rebound = StoryTagging {
        parent: TagReference {
            object: parent.0,
            generation: parent.1,
            key: Some(story_key(request)),
        },
        selected: request
            .paragraphs
            .iter()
            .flat_map(|p| {
                let figure = request
                    .figures
                    .iter()
                    .find(|f| f.caption_paragraph == p.id)
                    .and_then(|f| rebound_figures.get(&f.id))
                    .and_then(|b| b.source.clone());
                figure
                    .into_iter()
                    .chain(rebound_sources.get(&p.id).cloned().flatten())
            })
            .collect(),
        insert_at: Some(
            start
                .checked_add(residual_figures.len())
                .ok_or_else(|| fail("reused Figure insertion point overflow"))?,
        ),
        paragraph_sources: rebound_sources,
        new_roles: BTreeMap::new(),
        // The next edit must review meaning-dependent descriptions again. A
        // prior approval must not silently authorize stale wording indefinitely.
        semantic_text: BTreeMap::new(),
        figures: rebound_figures,
    };
    Ok((output, Some(rebound), None))
}

/// Bind newly inserted authored typed-cell carriers to the original logical
/// cell owner. Page insertion deliberately copies only page content/resources,
/// never a continuation document's unrelated structure tree. This transaction
/// resolves the stable table/cell pair in the destination structure tree,
/// appends one MCR for every actual marker on each new page, and rebuilds the
/// ParentTree from the completed graph before returning bytes.
pub(crate) fn attach_authored_typed_cell_fragments(
    input: &[u8],
    expected: &[(usize, String, String)],
) -> Result<Vec<u8>> {
    attach_authored_typed_cell_fragments_impl(input, expected, false)
}

/// Attach restored typed-cell carriers to a retained page that legitimately
/// contains other table owners. Exact requested identities must still appear
/// once and every page-local MCID must remain unique.
pub(crate) fn attach_authored_typed_cell_fragments_to_existing_pages(
    input: &[u8],
    expected: &[(usize, String, String)],
) -> Result<Vec<u8>> {
    attach_authored_typed_cell_fragments_impl(input, expected, true)
}

fn attach_authored_typed_cell_fragments_impl(
    input: &[u8],
    expected: &[(usize, String, String)],
    allow_unrelated_owners: bool,
) -> Result<Vec<u8>> {
    if expected.is_empty() {
        return Ok(input.to_vec());
    }
    if expected.len() > 1_000_000 {
        return Err(WellfriendError::ResourceLimit(
            "authored typed-cell continuation ownership count".into(),
        ));
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (mut store, _, index) = index_document(&engine, None)?;
    let pages = engine.document().get_pages()?;
    let mut owners = BTreeMap::<(String, String), ObjectRef>::new();
    for &node in &index.nodes {
        let dictionary = store.dict(node)?;
        let table = dictionary
            .get("WFTableID")
            .and_then(PdfObject::as_string)
            .map(crate::info::decode_pdf_text_string);
        let cell = dictionary
            .get("WFCellID")
            .and_then(PdfObject::as_string)
            .map(crate::info::decode_pdf_text_string);
        if table.is_some() != cell.is_some() {
            return Err(fail(
                "typed-cell structure owner has incomplete stable identity",
            ));
        }
        if let Some(key) = table.zip(cell) {
            if owners.insert(key, node).is_some() {
                return Err(fail(
                    "typed-cell structure identity resolves to multiple owners",
                ));
            }
        }
    }

    let mut additions = BTreeMap::<ObjectRef, Vec<PdfObject>>::new();
    let mut by_page = BTreeMap::<usize, BTreeSet<(String, String)>>::new();
    for (page_number, table, cell) in expected {
        if !by_page
            .entry(*page_number)
            .or_default()
            .insert((table.clone(), cell.clone()))
        {
            return Err(fail("duplicate authored typed-cell continuation request"));
        }
    }
    for (page_number, expected_cells) in by_page {
        crate::cancel::check_current_cancel("authored typed-cell structure growth")?;
        let page = pages
            .get(page_number.saturating_sub(1))
            .filter(|page| page.page_number == page_number)
            .ok_or_else(|| fail("authored typed-cell continuation page is missing"))?;
        let page_id = (page.object_number, page.generation_number);
        let marks = page_marks(&engine, page)?;
        let mut observed = BTreeMap::<(String, String), Vec<usize>>::new();
        let mut used_mcids = BTreeSet::new();
        for mark in &marks.marks {
            if allow_unrelated_owners {
                if let Some(mcid) = mark.mcid {
                    if !used_mcids.insert(mcid) {
                        return Err(fail(
                            "restored authored typed-cell page reuses an existing MCID",
                        ));
                    }
                }
            }
            let Some(key) = mark.authored_table.clone().zip(mark.authored_cell.clone()) else {
                continue;
            };
            if !expected_cells.contains(&key) {
                if allow_unrelated_owners {
                    continue;
                }
                return Err(fail(
                    "authored typed-cell continuation page contains an unexpected owner",
                ));
            }
            let mcid = mark.mcid.ok_or_else(|| {
                fail("authored typed-cell continuation lacks a direct MCID carrier")
            })?;
            if !allow_unrelated_owners && !used_mcids.insert(mcid) {
                return Err(fail("authored typed-cell continuation page reuses an MCID"));
            }
            observed.entry(key).or_default().push(mcid);
        }
        for key in expected_cells {
            let owner = owners
                .get(&key)
                .copied()
                .ok_or_else(|| fail("authored typed-cell structure owner is missing"))?;
            let mcids = observed
                .remove(&key)
                .filter(|mcids| !mcids.is_empty())
                .ok_or_else(|| {
                    fail("authored typed-cell continuation owner has no content marker")
                })?;
            for mcid in mcids {
                let mut mcr = PdfDictionary::empty();
                mcr.insert("Type", PdfObject::Name("MCR".into()));
                mcr.insert("Pg", reference(page_id));
                mcr.insert("MCID", PdfObject::Integer(mcid as i64));
                additions
                    .entry(owner)
                    .or_default()
                    .push(PdfObject::Dictionary(mcr));
            }
        }
        if !observed.is_empty() {
            return Err(fail(
                "authored typed-cell continuation ownership was not consumed exactly",
            ));
        }
    }

    for (owner, items) in additions {
        let mut dictionary = store.dict(owner)?;
        let mut children = kids(&dictionary);
        children.extend(items);
        dictionary.insert("K", PdfObject::Array(children));
        dictionary.remove("Pg");
        store.replace_dict(owner, dictionary)?;
    }
    let candidate = write_store(store)?;
    let (output, _) = rebuild_owner_trees(&candidate, None)?;
    validate_parent_tree(&output)?;
    Ok(output)
}

#[derive(Debug, Clone)]
pub(crate) struct AuthoredTypedContinuationPageInspection {
    /// SHA-256 over every decoded content-stream byte outside exact typed-cell
    /// scopes. Cell edits may change their owned scopes; page furniture and
    /// every unrelated byte must remain identical to the creation receipt.
    pub static_digest: String,
    /// True only when every text operand in every expected cell is empty and
    /// all remaining paint is a non-image artifact outside those cell scopes.
    pub empty: bool,
    /// A relocation destination may contain expected text inside its owned
    /// cells, but never an image/path/other visual object hidden inside those
    /// same scopes. Such content is not authorized by a typed-cell receipt.
    pub owned_nontext: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct AuthoredTypedCellSourceScope {
    pub page: usize,
    pub stream: ObjectRef,
    pub decoded_range: [usize; 2],
    pub cell_id: String,
}

/// Resolve exact page-content marked-content scopes for a selected subset of
/// authored typed cells. Other typed owners on the same page are preserved and
/// ignored. This is relocation provenance, never a geometry/text heuristic.
pub(crate) fn inspect_authored_typed_cell_source_scopes(
    input: &[u8],
    table_id: &str,
    cell_ids: &BTreeSet<String>,
    page_numbers: &BTreeSet<usize>,
) -> Result<Vec<AuthoredTypedCellSourceScope>> {
    if table_id.is_empty()
        || cell_ids.is_empty()
        || cell_ids.len() > 4096
        || page_numbers.is_empty()
        || page_numbers.len() > 10_000
    {
        return Err(fail("invalid authored typed-cell source-scope request"));
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let mut output = Vec::new();
    for &page_number in page_numbers {
        crate::cancel::check_current_cancel("authored typed-cell source-scope inspection")?;
        let page = engine.document().get_page(page_number)?;
        let marks = page_marks(&engine, &page)?;
        let mut seen = BTreeSet::new();
        for mark in marks.marks {
            let Some((table, cell)) = mark
                .authored_table
                .as_deref()
                .zip(mark.authored_cell.as_deref())
            else {
                continue;
            };
            if table != table_id || !cell_ids.contains(cell) {
                continue;
            }
            if !mark.safe || mark.mcid.is_none() {
                return Err(fail(
                    "authored typed-cell relocation scope is unsafe or lacks an MCID",
                ));
            }
            let (closing_stream, _, closing_end) = mark
                .closing
                .ok_or_else(|| fail("authored typed-cell relocation scope is unterminated"))?;
            if closing_stream != mark.stream || mark.start >= closing_end {
                return Err(fail(
                    "authored typed-cell relocation scope crosses content streams",
                ));
            }
            seen.insert(cell.to_owned());
            output.push(AuthoredTypedCellSourceScope {
                page: page_number,
                stream: mark.stream,
                decoded_range: [mark.start, closing_end],
                cell_id: cell.to_owned(),
            });
        }
        if &seen != cell_ids {
            return Err(fail(
                "authored typed-cell relocation scope set is incomplete",
            ));
        }
    }
    if output.len() > 1_000_000 {
        return Err(WellfriendError::ResourceLimit(
            "authored typed-cell relocation scope count".into(),
        ));
    }
    output.sort_by_key(|scope| (scope.page, scope.stream, scope.decoded_range));
    Ok(output)
}

/// Return the first page-local MCID not already used by any retained marked
/// content scope. Backward table compaction appends new source carriers to an
/// existing authored page and must never recycle an MCID that still belongs to
/// another structure owner.
pub(crate) fn next_page_mcid(input: &[u8], page_number: usize) -> Result<u32> {
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let page = engine.document().get_page(page_number)?;
    let marks = page_marks(&engine, &page)?;
    let mut used = BTreeSet::new();
    for mark in marks.marks {
        let Some(mcid) = mark.mcid else {
            continue;
        };
        if !used.insert(mcid) {
            return Err(fail("authored page reuses an MCID before compaction"));
        }
    }
    used.into_iter().next_back().map_or(Ok(0), |mcid| {
        u32::try_from(mcid)
            .ok()
            .and_then(|value| value.checked_add(1))
            .ok_or_else(|| WellfriendError::ResourceLimit("authored page MCID space".into()))
    })
}

/// Inspect a bounded set of typed-table continuation pages in one document
/// parse. Exact cell scopes are excluded from the static digest but remain
/// subject to semantic emptiness checks. This is deliberately stricter than
/// extraction: unrelated text, unmarked paint, images, duplicate/missing cell
/// markers or additional typed owners make the page ineligible for pruning.
pub(crate) fn inspect_authored_typed_cell_continuation_pages(
    input: &[u8],
    table_id: &str,
    cell_ids: &BTreeSet<String>,
    page_numbers: &BTreeSet<usize>,
) -> Result<BTreeMap<usize, AuthoredTypedContinuationPageInspection>> {
    inspect_authored_typed_cell_continuation_pages_impl(
        input,
        table_id,
        cell_ids,
        page_numbers,
        true,
    )
}

/// Inspect a nested relocation destination after a verified child transaction
/// has moved some of the parent's cells onward. Any observed typed owner must
/// still belong to the receipt, but missing receipt cells are permitted because
/// their exact scopes are no longer present on this page.
pub(crate) fn inspect_authored_typed_cell_continuation_page_subset(
    input: &[u8],
    table_id: &str,
    cell_ids: &BTreeSet<String>,
    page_numbers: &BTreeSet<usize>,
) -> Result<BTreeMap<usize, AuthoredTypedContinuationPageInspection>> {
    inspect_authored_typed_cell_continuation_pages_impl(
        input,
        table_id,
        cell_ids,
        page_numbers,
        false,
    )
}

fn inspect_authored_typed_cell_continuation_pages_impl(
    input: &[u8],
    table_id: &str,
    cell_ids: &BTreeSet<String>,
    page_numbers: &BTreeSet<usize>,
    require_all_cells: bool,
) -> Result<BTreeMap<usize, AuthoredTypedContinuationPageInspection>> {
    if table_id.is_empty()
        || cell_ids.is_empty()
        || cell_ids.len() > 4096
        || page_numbers.is_empty()
        || page_numbers.len() > 10_000
    {
        return Err(fail(
            "invalid authored typed-cell continuation inspection request",
        ));
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let mut output = BTreeMap::new();
    for &page_number in page_numbers {
        crate::cancel::check_current_cancel("authored typed-cell continuation inspection")?;
        let page = engine.document().get_page(page_number)?;
        if page.contents.len() > 4096
            || page.contents.iter().copied().collect::<BTreeSet<_>>().len() != page.contents.len()
        {
            return Err(fail(
                "authored typed-cell continuation has duplicate or excessive content streams",
            ));
        }
        let marks = page_marks(&engine, &page)?;
        let mut seen = BTreeSet::new();
        let mut typed_marks = BTreeSet::new();
        let mut ranges = BTreeMap::<ObjectRef, Vec<(usize, usize)>>::new();
        let mut nested_marks = Vec::new();
        let mut empty = true;
        let mut owned_nontext = false;
        for (index, mark) in marks.marks.iter().enumerate() {
            match mark
                .authored_table
                .as_deref()
                .zip(mark.authored_cell.as_deref())
            {
                Some((table, cell)) if table == table_id && cell_ids.contains(cell) => {
                    if !mark.safe || mark.mcid.is_none() || !seen.insert(cell.to_owned()) {
                        return Err(fail(
                            "authored typed-cell continuation owner is duplicated or unsafe",
                        ));
                    }
                    let (closing_stream, _, closing_end) = mark.closing.ok_or_else(|| {
                        fail("authored typed-cell continuation owner is unterminated")
                    })?;
                    if closing_stream != mark.stream || mark.start >= closing_end {
                        return Err(fail(
                            "authored typed-cell continuation owner crosses content streams",
                        ));
                    }
                    typed_marks.insert(index);
                    ranges
                        .entry(mark.stream)
                        .or_default()
                        .push((mark.start, closing_end));
                }
                Some(_) => {
                    return Err(fail(
                        "authored typed-cell continuation page contains another typed owner",
                    ));
                }
                None if !mark.artifact => nested_marks.push(index),
                None => {}
            }
        }
        if require_all_cells && &seen != cell_ids {
            return Err(fail(
                format!(
                    "authored typed-cell continuation page {page_number} does not contain every expected cell; observed={seen:?}; expected={cell_ids:?}"
                ),
            ));
        }
        for index in nested_marks {
            let mark = &marks.marks[index];
            let inside_artifact = marks.marks.iter().any(|outer| {
                outer.artifact
                    && outer.stream == mark.stream
                    && outer.start <= mark.start
                    && outer.closing.is_some_and(|(stream, _, outer_end)| {
                        stream == mark.stream
                            && mark.closing.is_some_and(|(inner_stream, _, inner_end)| {
                                inner_stream == mark.stream && inner_end <= outer_end
                            })
                    })
            });
            if inside_artifact {
                continue;
            }
            let nested = mark.closing.is_some_and(|(stream, _, end)| {
                stream == mark.stream
                    && ranges.get(&stream).is_some_and(|owners| {
                        owners
                            .iter()
                            .any(|&(start, owner_end)| start <= mark.start && end <= owner_end)
                    })
            });
            if !nested
                || mark.mcid.is_some()
                || mark.actual_text_nonempty
                || mark.frame.is_some()
                || mark.paragraph.is_some()
                || mark.image_key.is_some()
                || mark.figure.is_some()
            {
                empty = false;
            }
        }
        for occurrence in &marks.text {
            let owned = occurrence
                .marks
                .iter()
                .any(|index| typed_marks.contains(index));
            let artifact = occurrence
                .marks
                .iter()
                .any(|index| marks.marks[*index].artifact);
            if (owned && !occurrence.bytes_empty) || (!owned && !artifact) {
                empty = false;
            }
        }
        for occurrence in &marks.nontext {
            let owned = occurrence
                .marks
                .iter()
                .any(|index| typed_marks.contains(index));
            let artifact = occurrence
                .marks
                .iter()
                .any(|index| marks.marks[*index].artifact);
            if owned || !artifact || occurrence.image {
                empty = false;
            }
            if owned {
                owned_nontext = true;
            }
        }

        let mut decoded = ContentScopes::new(&engine);
        let mut digest = Sha256::new();
        digest.update(b"wellfriend.authored-typed-table.static-content.v1");
        digest.update((page.contents.len() as u64).to_be_bytes());
        for (stream_index, &stream) in page.contents.iter().enumerate() {
            let data = decoded.stream(stream)?;
            let mut owned = ranges.remove(&stream).unwrap_or_default();
            owned.sort_unstable();
            if owned.windows(2).any(|pair| pair[0].1 > pair[1].0)
                || owned
                    .iter()
                    .any(|&(start, end)| start >= end || end > data.len())
            {
                return Err(fail(
                    "authored typed-cell continuation owner ranges overlap or escape their stream",
                ));
            }
            digest.update((stream_index as u64).to_be_bytes());
            digest.update(((owned.len() + 1) as u64).to_be_bytes());
            let mut cursor = 0usize;
            for (start, end) in owned {
                let static_bytes = &data[cursor..start];
                digest.update((static_bytes.len() as u64).to_be_bytes());
                digest.update(static_bytes);
                cursor = end;
            }
            let static_bytes = &data[cursor..];
            digest.update((static_bytes.len() as u64).to_be_bytes());
            digest.update(static_bytes);
        }
        if !ranges.is_empty() {
            return Err(fail(
                "authored typed-cell continuation owner references an unlisted stream",
            ));
        }
        output.insert(
            page_number,
            AuthoredTypedContinuationPageInspection {
                static_digest: format!("{:x}", digest.finalize()),
                empty,
                owned_nontext,
            },
        );
    }
    Ok(output)
}

/// Return the exact structure owners which may shed page-local MCR children
/// during table continuation pruning. The caller may use these only as scoped
/// departures while checking incoming page references.
pub(crate) fn authored_typed_cell_owner_nodes(
    input: &[u8],
    table_id: &str,
    cell_ids: &BTreeSet<String>,
) -> Result<BTreeSet<ObjectRef>> {
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (store, _, index) = index_document(&engine, None)?;
    let mut owners = BTreeMap::<String, ObjectRef>::new();
    for &node in &index.nodes {
        let dictionary = store.dict(node)?;
        let table = dictionary
            .get("WFTableID")
            .and_then(PdfObject::as_string)
            .map(crate::info::decode_pdf_text_string);
        let cell = dictionary
            .get("WFCellID")
            .and_then(PdfObject::as_string)
            .map(crate::info::decode_pdf_text_string);
        if table.as_deref() == Some(table_id) {
            let cell = cell.ok_or_else(|| fail("typed-cell owner identity is incomplete"))?;
            if cell_ids.contains(&cell) && owners.insert(cell, node).is_some() {
                return Err(fail("typed-cell continuation owner identity is duplicated"));
            }
        }
    }
    if owners.keys().collect::<BTreeSet<_>>() != cell_ids.iter().collect::<BTreeSet<_>>() {
        return Err(fail(
            "typed-cell continuation structure owner set is incomplete",
        ));
    }
    Ok(owners.into_values().collect())
}

/// Remove only the exact page-local MCR children selected by stable table/cell
/// identity. Other typed owners on a retained page are left untouched. The
/// logical TH/TD owners themselves survive; the ParentTree is rebuilt and
/// validated before relocation or page-tree pruning proceeds.
pub(crate) fn detach_authored_typed_cell_fragments(
    input: &[u8],
    expected: &[(usize, String, String)],
) -> Result<Vec<u8>> {
    if expected.is_empty() || expected.len() > 1_000_000 {
        return Err(fail(
            "invalid authored typed-cell continuation detachment request",
        ));
    }
    let engine = ContentEngine::open_bytes(input.to_vec())?;
    let (mut store, _, index) = index_document(&engine, None)?;
    let pages = engine.document().get_pages()?;
    let mut owners = BTreeMap::<(String, String), ObjectRef>::new();
    for &node in &index.nodes {
        let dictionary = store.dict(node)?;
        let table = dictionary
            .get("WFTableID")
            .and_then(PdfObject::as_string)
            .map(crate::info::decode_pdf_text_string);
        let cell = dictionary
            .get("WFCellID")
            .and_then(PdfObject::as_string)
            .map(crate::info::decode_pdf_text_string);
        if table.is_some() != cell.is_some() {
            return Err(fail(
                "typed-cell structure owner has incomplete stable identity",
            ));
        }
        if let Some(key) = table.zip(cell) {
            if owners.insert(key, node).is_some() {
                return Err(fail(
                    "typed-cell structure identity resolves to multiple owners",
                ));
            }
        }
    }
    let mut by_page = BTreeMap::<usize, BTreeSet<(String, String)>>::new();
    for (page, table, cell) in expected {
        if !by_page
            .entry(*page)
            .or_default()
            .insert((table.clone(), cell.clone()))
        {
            return Err(fail("duplicate authored typed-cell detachment request"));
        }
    }
    let mut removals = BTreeMap::<ObjectRef, BTreeSet<(ObjectRef, usize)>>::new();
    for (page_number, expected_cells) in by_page {
        crate::cancel::check_current_cancel("authored typed-cell structure contraction")?;
        let page = pages
            .get(page_number.saturating_sub(1))
            .filter(|page| page.page_number == page_number)
            .ok_or_else(|| fail("authored typed-cell contraction page is missing"))?;
        let page_id = (page.object_number, page.generation_number);
        let marks = page_marks(&engine, page)?;
        let mut observed = BTreeMap::<(String, String), BTreeSet<usize>>::new();
        for mark in &marks.marks {
            let Some(key) = mark.authored_table.clone().zip(mark.authored_cell.clone()) else {
                continue;
            };
            if !expected_cells.contains(&key) {
                continue;
            }
            let mcid = mark
                .mcid
                .ok_or_else(|| fail("authored typed-cell contraction owner has no MCID"))?;
            if !observed.entry(key).or_default().insert(mcid) {
                return Err(fail(
                    "authored typed-cell contraction page duplicates an MCID",
                ));
            }
        }
        for key in expected_cells {
            let owner = owners
                .get(&key)
                .copied()
                .ok_or_else(|| fail("authored typed-cell contraction owner is missing"))?;
            let mcids = observed
                .remove(&key)
                .filter(|mcids| !mcids.is_empty())
                .ok_or_else(|| fail("authored typed-cell contraction marker is missing"))?;
            removals
                .entry(owner)
                .or_default()
                .extend(mcids.into_iter().map(|mcid| (page_id, mcid)));
        }
        if !observed.is_empty() {
            return Err(fail(
                "authored typed-cell contraction ownership was not consumed exactly",
            ));
        }
    }
    for (owner, targets) in removals {
        let mut dictionary = store.dict(owner)?;
        let mut removed = BTreeSet::new();
        let mut retained = Vec::new();
        for child in kids(&dictionary) {
            let resolved = store.resolve(&child)?;
            let key = resolved.as_dict().and_then(|mcr| {
                (mcr.get_name("Type") == Some("MCR"))
                    .then(|| {
                        Some((
                            mcr.get_reference("Pg")?,
                            usize::try_from(mcr.get_integer("MCID")?).ok()?,
                        ))
                    })
                    .flatten()
            });
            if key.is_some_and(|key| targets.contains(&key)) {
                if !removed.insert(key.expect("matched MCR key")) {
                    return Err(fail(
                        "authored typed-cell contraction duplicates a structure MCR",
                    ));
                }
            } else {
                retained.push(child);
            }
        }
        if removed != targets || retained.is_empty() {
            return Err(fail(
                "authored typed-cell contraction could not detach its exact MCR set",
            ));
        }
        dictionary.insert("K", PdfObject::Array(retained));
        dictionary.remove("Pg");
        store.replace_dict(owner, dictionary)?;
    }
    // Deliberately return the structure half of the transaction without
    // rebuilding or validating the ParentTree yet. The selected MCID carriers
    // still exist in page content at this point, so validating this private
    // intermediate revision would necessarily report an ownership mismatch.
    // The table transaction removes the exact content scopes (or their whole
    // pages) next and must then call `finalize_authored_typed_cell_transaction`.
    write_store(store)
}

/// Complete a staged typed-cell detach after its exact content carriers have
/// been removed. The owner trees are rebuilt from the now-consistent structure
/// graph and page content, and the canonical validator reopens the result.
pub(crate) fn finalize_authored_typed_cell_transaction(input: &[u8]) -> Result<Vec<u8>> {
    rebuild_owner_trees(input, None).map(|(output, _)| output)
}

